#!/usr/bin/env python3
"""Regenerate src/main/java/.../core/ZigguratTables.java from numpy's ziggurat_constants.h.
Usage: python gen_ziggurat_tables.py <numpy-src>/numpy/random/src/distributions/ziggurat_constants.h <out.java>"""
import re, sys
h = open(sys.argv[1]).read()
def arr(name):
    m = re.search(r"static const \w+ " + name + r"\[\] = \{(.*?)\};", h, re.S)
    return [x.strip() for x in m.group(1).replace("\n", " ").split(",") if x.strip()]
ki, wi, fi = arr("ki_double"), arr("wi_double"), arr("fi_double")
jl = lambda v: v.replace("ULL", "L").replace("UL", "L")
jd = lambda v: v.rstrip("fF")
out = ["package org.geoframe.interpolation.pokriging.core;", "", "/**",
       " * Ziggurat tables of numpy's {@code random_standard_normal} (float64), copied verbatim from",
       " * numpy/random/src/distributions/ziggurat_constants.h (numpy 2.4.6, BSD-3-Clause licence,",
       " * Copyright (c) 2005-2025 NumPy Developers). Generated by tools/gen_ziggurat_tables.py; do not edit.", " */",
       "final class ZigguratTables {", "    private ZigguratTables() { }",
       "    static final double ZIGGURAT_NOR_R = 3.6541528853610087963519472518;",
       "    static final double ZIGGURAT_NOR_INV_R = 0.27366123732975827203338247596;"]
for nm, vals, f, t in (("KI", ki, jl, "long"), ("WI", wi, jd, "double"), ("FI", fi, jd, "double")):
    out.append(f"    static final {t}[] {nm} = {{")
    for i in range(0, len(vals), 4): out.append("        " + ", ".join(f(v) for v in vals[i:i + 4]) + ",")
    out.append("    };")
out.append("}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("written", sys.argv[2], len(ki), len(wi), len(fi))
